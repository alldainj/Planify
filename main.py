@app.post("/api/auth/register")
async def register(data: AuthData, response: Response):
    username = data.username.strip()

    if len(username) < 3 or len(username) > 30:
        raise HTTPException(
            status_code=400,
            detail="Имя пользователя должно содержать от 3 до 30 символов."
        )

    if any(ord(char) < 32 for char in username):
        raise HTTPException(
            status_code=400,
            detail="Имя пользователя содержит недопустимые символы."
        )

    if len(data.password) < 8:
        raise HTTPException(
            status_code=400,
            detail="Пароль должен содержать минимум 8 символов."
        )

    salt = secrets.token_hex(16)
    password_hash = hash_password(data.password, salt)

    try:
        with get_db() as db:
            cursor = db.execute("""
                INSERT INTO users (
                    username,
                    password_hash,
                    password_salt,
                    created_at
                )
                VALUES (%s, %s, %s, %s)
                RETURNING id
            """, (
                username,
                password_hash,
                salt,
                datetime.now(timezone.utc)
            ))

            user_id = cursor.fetchone()["id"]

    except UniqueViolation:
        raise HTTPException(
            status_code=409,
            detail="Такое имя пользователя уже занято."
        )

    create_session(user_id, response)

    return {
        "success": True,
        "username": username
    }


