@app.post("/api/auth/logout")
async def logout(request: Request, response: Response):
    token = request.cookies.get("planify_session")

    if token:
        with get_db() as db:
            db.execute("""
                DELETE FROM sessions
                WHERE token_hash = %s
            """, (hash_token(token),))

    response.delete_cookie(
        key="planify_session",
        path="/",
        httponly=True,
        samesite="strict",
        secure=COOKIE_SECURE
    )

    return {
        "success": True
    }


