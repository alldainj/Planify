@app.get("/api/events")
async def get_events(request: Request):
    user = require_user(request)

    with get_db() as db:
        row = db.execute("""
            SELECT events_json
            FROM user_events
            WHERE user_id = %s
        """, (user["id"],)).fetchone()

    if not row:
        return {
            "events": []
        }

    events = row["events_json"]

    if not isinstance(events, list):
        events = []

    return {
        "events": events
    }


