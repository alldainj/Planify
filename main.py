@app.post("/api/auth/login")
async def login(data: AuthData, response: Response):
    username = data.username.strip()

    with get_db() as db:
        user = db.execute("""
            SELECT *
            FROM users
            WHERE lower(username) = lower(%s)
        """, (username,)).fetchone()

    if not user:
        raise HTTPException(
            status_code=401,
            detail="Неверное имя пользователя или пароль."
        )

    if not verify_password(
        data.password,
        user["password_salt"],
        user["password_hash"]
    ):
        raise HTTPException(
            status_code=401,
            detail="Неверное имя пользователя или пароль."
        )

    create_session(user["id"], response)

    return {
        "success": True,
        "username": user["username"]
    }


