@app.put("/api/events")
async def save_events(
    data: EventsData,
    request: Request
):
    user = require_user(request)

    events_json = json.dumps(
        data.events,
        ensure_ascii=False
    )

    updated_at = datetime.now(timezone.utc)

    with get_db() as db:
        db.execute("""
            INSERT INTO user_events (
                user_id,
                events_json,
                updated_at
            )
            VALUES (%s, %s::jsonb, %s)

            ON CONFLICT(user_id)
            DO UPDATE SET
                events_json = EXCLUDED.events_json,
                updated_at = EXCLUDED.updated_at
        """, (
            user["id"],
            events_json,
            updated_at
        ))

    return {
        "success": True,
        "count": len(data.events)
    }


