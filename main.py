@app.get("/", response_class=HTMLResponse)
async def home(request: Request):
    template = templates.env.get_template("index.html")

    html = template.render(
        request=request,
        context={}
    )

    auth_script = '<script src="/static/js/auth.js"></script>'

    original_script = '<script src="/static/js/script.js"></script>'

    if original_script in html:
        html = html.replace(
            original_script,
            auth_script + "\n" + original_script
        )
    else:
        html = html.replace(
            "</body>",
            auth_script + "\n</body>"
        )

    return HTMLResponse(content=html)
